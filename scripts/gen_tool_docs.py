"""Generate README tool tables from isolated, actually registered MCP schemas.

No AWX configuration, credential lookup, startup validation or requests are
needed. ``--check`` computes the same output without writing any file.
"""

from __future__ import annotations

import argparse
import inspect
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import anyio
from mcp.server.mcpserver import MCPServer

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from awx_mcp import server  # noqa: E402
from awx_mcp.settings import Settings  # noqa: E402

READMES = ("README.md", "README.ko.md", "README.ja.md")


@dataclass(frozen=True)
class ToolDoc:
    name: str
    toolset: str
    read_only: bool
    opt_in: bool
    summary: str
    input_schema: dict[str, Any]


@dataclass(frozen=True)
class Catalog:
    tools: tuple[ToolDoc, ...]

    @property
    def total_count(self) -> int:
        return len(self.tools)

    @property
    def default_count(self) -> int:
        return sum(not tool.opt_in for tool in self.tools)

    @property
    def toolsets(self) -> tuple[str, ...]:
        return tuple(sorted({tool.toolset for tool in self.tools}))


def summarize(doc: str) -> str:
    """Keep the original English first sentence, safe inside a Markdown cell."""
    paragraph = inspect.cleandoc(doc).split("\n\n", 1)[0]
    paragraph = " ".join(paragraph.split())
    sentence = re.split(r"(?<=[.!?])\s+", paragraph, maxsplit=1)[0]
    return sentence.replace("|", r"\|")


def load_catalog() -> Catalog:
    default_server = MCPServer("awx-docs-default")
    defaults = set(server.register_tools(default_server, Settings.from_env({})))
    all_server = MCPServer("awx-docs-all")
    server.register_tools(
        all_server,
        Settings.from_env({}, overrides={"enable_credential_management": True}),
    )
    schemas = anyio.run(all_server.list_tools)
    specs = {spec.func.__name__: spec for spec in server._REGISTRY}
    tools = []
    for schema in schemas:
        spec = specs[schema.name]
        tools.append(
            ToolDoc(
                name=schema.name,
                toolset=spec.toolset,
                read_only=bool(
                    schema.annotations and schema.annotations.read_only_hint
                ),
                opt_in=schema.name not in defaults,
                summary=summarize(inspect.getdoc(spec.func) or ""),
                input_schema=schema.input_schema,
            )
        )
    return Catalog(tuple(sorted(tools, key=lambda tool: (tool.toolset, tool.name))))


def render_tables(catalog: Catalog) -> str:
    lines = [
        "<!-- Generated by scripts/gen_tool_docs.py. Do not edit by hand. -->",
        "",
    ]
    for toolset in catalog.toolsets:
        tools = [tool for tool in catalog.tools if tool.toolset == toolset]
        default = sum(not tool.opt_in for tool in tools)
        lines.extend(
            [
                f"### `{toolset}` ({len(tools)} tools, {default} default)",
                "",
                "| Tool | Access | Summary |",
                "|------|--------|---------|",
            ]
        )
        for tool in tools:
            access = "Read" if tool.read_only else "Write"
            if tool.opt_in:
                access += " (opt-in)"
            lines.append(f"| `{tool.name}` | {access} | {tool.summary} |")
        lines.append("")
    return "\n".join(lines).rstrip()


def render_summary(catalog: Catalog) -> str:
    lines = [
        "<!-- Generated by scripts/gen_tool_docs.py. Do not edit by hand. -->",
        "",
        "| Toolset | Default tools | With credential opt-in |",
        "|---------|---------------|------------------------|",
    ]
    for toolset in catalog.toolsets:
        tools = [tool for tool in catalog.tools if tool.toolset == toolset]
        default = sum(not tool.opt_in for tool in tools)
        lines.append(f"| `{toolset}` | {default} | {len(tools)} |")
    return "\n".join(lines)


def replace_region(content: str, name: str, rendered: str) -> str:
    begin, end = f"<!-- {name}:BEGIN -->", f"<!-- {name}:END -->"
    if content.count(begin) != 1 or content.count(end) != 1:
        raise ValueError(f"{name} requires exactly one BEGIN/END marker pair")
    before, rest = content.split(begin)
    old, after = rest.split(end)
    if begin in old or end in before:
        raise ValueError(f"{name} markers are out of order")
    return before + begin + "\n" + rendered + "\n" + end + after



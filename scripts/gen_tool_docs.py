def sync_counts(content: str, catalog: Catalog) -> str:
    values = {
        "total": catalog.total_count,
        "default": catalog.default_count,
        "opt_in": catalog.total_count - catalog.default_count,
        "toolsets": len(catalog.toolsets),
    }

    def replace(match: re.Match[str]) -> str:
        text = match.group()
        # Replace from right to left so earlier offsets remain valid.
        for group in sorted(match.groupdict(), key=match.start, reverse=True):
            start = match.start(group) - match.start()
            end = match.end(group) - match.start()
            text = text[:start] + str(values[group]) + text[end:]
        return text

    for pattern in COUNT_PATTERNS:
        content = re.sub(pattern, replace, content, flags=re.MULTILINE)
    return content


def generate(root: Path, *, check: bool = False) -> int:
    catalog = load_catalog()
    updates = {}
    # Validate and render everything first. A malformed later document cannot
    # leave earlier documents partially updated.
    for name in READMES:
        path = root / name
        content = path.read_text(encoding="utf-8")
        rendered = replace_region(content, "TOOL_TABLES", render_tables(catalog))
        rendered = replace_region(rendered, "TOOLSET_SUMMARY", render_summary(catalog))
        rendered = sync_counts(rendered, catalog)
        if rendered != content:
            updates[path] = rendered
    for name in ("SECURITY.md", "pyproject.toml"):
        path = root / name
        content = path.read_text(encoding="utf-8")
        rendered = sync_counts(content, catalog)
        if rendered != content:
            updates[path] = rendered
    if check:
        for path in updates:
            print(
                f"STALE: {path.name}. Run uv run python scripts/gen_tool_docs.py",
                file=sys.stderr,
            )
        return int(bool(updates))
    for path, rendered in updates.items():
        path.write_text(rendered, encoding="utf-8")
    print(
        f"OK: {catalog.total_count} tools ({catalog.default_count} default), "
        f"{len(catalog.toolsets)} toolsets; updated {len(updates)} files"
    )
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="Fail on stale docs without writing"
    )
    parser.add_argument("--root", type=Path, default=ROOT, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    try:
        return generate(args.root, check=args.check)
    except (ValueError, OSError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
